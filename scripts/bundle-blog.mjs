// Bundles content/blog into the build, because the Worker has no file system.
// content/blog/*.md are the posts; content/blog/id/*.md are Indonesian versions
// of the short ones, under the same file name.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIR = join(ROOT, "content", "blog");

function read(dir) {
  if (!existsSync(dir)) return {};
  return Object.fromEntries(
    readdirSync(dir)
      .filter((f) => f.endsWith(".md"))
      .sort()
      .map((f) => [f.replace(/\.md$/, ""), readFileSync(join(dir, f), "utf8")]),
  );
}

writeFileSync(
  join(ROOT, "src", "lib", "blog-content.generated.ts"),
  "// Generated by scripts/bundle-blog.mjs from content/blog. Do not edit.\n" +
    `export const BLOG_SOURCES: Record<string, string> = ${JSON.stringify(read(DIR), null, 2)};\n` +
    `export const BLOG_SOURCES_ID: Record<string, string> = ${JSON.stringify(read(join(DIR, "id")), null, 2)};\n`,
);
