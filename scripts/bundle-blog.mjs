// Bundles content/blog/*.md into src/lib/blog-content.generated.ts.
// The Worker has no file system, so the posts travel inside the build.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIR = join(ROOT, "content", "blog");
const posts = Object.fromEntries(
  readdirSync(DIR)
    .filter((f) => f.endsWith(".md"))
    .sort()
    .map((f) => [f.replace(/\.md$/, ""), readFileSync(join(DIR, f), "utf8")]),
);
writeFileSync(
  join(ROOT, "src", "lib", "blog-content.generated.ts"),
  `// Generated by scripts/bundle-blog.mjs from content/blog. Do not edit.\nexport const BLOG_SOURCES: Record<string, string> = ${JSON.stringify(posts, null, 2)};\n`,
);
